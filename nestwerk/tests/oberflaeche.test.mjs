// Neue Oberfläche im echten Browser prüfen:  node tests/oberflaeche.test.mjs  (Testserver auf :4173)
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
let fails = 0
const ok = (c, m, x) => { console.log((c ? 'OK: ' : 'FAIL: ') + m + (c || x === undefined ? '' : '  → ' + JSON.stringify(x))); if (!c) fails++ }
const iso = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
const nextWd = (wd) => { const d = new Date(); const cur = (d.getDay() + 6) % 7; d.setDate(d.getDate() + ((wd - cur + 7) % 7)); return iso(d) }

const ctx = await browser.newContext({ viewport: { width: 1360, height: 900 } })
const page = await ctx.newPage()
const errs = []
page.on('pageerror', (e) => errs.push(e.message))
const store = () => page.evaluate(() => JSON.parse(localStorage.getItem('eselsohr-v1')))
await page.goto('http://localhost:4173')
await page.evaluate(() => localStorage.clear())
await page.reload(); await page.waitForTimeout(300)
await page.locator('button', { hasText: 'Erst mal die Demo ansehen' }).click()
await page.waitForTimeout(600)
await page.evaluate(() => { window.__wa = null; window.open = (u) => { window.__wa = u; return null } })

console.log('— Suche')
await page.keyboard.press('Control+k')
await page.waitForTimeout(250)
ok(await page.locator('.pal').isVisible(), 'Strg+K öffnet die Suche')
await page.keyboard.type('Emma morgen', { delay: 5 })
await page.waitForTimeout(150)
ok((await page.locator('.pal-mirror .tk-person').textContent()) === 'Emma' && (await page.locator('.pal-mirror .tk-date').textContent()) === 'morgen', 'Erkannte Wörter werden in der Eingabe eingefärbt')
await page.fill('#suche-eingabe', '')
await page.keyboard.type('Kla', { delay: 5 })
await page.waitForTimeout(120)
ok((await page.locator('.pal-mirror .ghost').textContent()) === 'vierstunde', 'Geisterschrift schlägt „Klavierstunde“ vor')
await page.keyboard.press('Tab')
ok((await page.inputValue('#suche-eingabe')) === 'Klavierstunde', 'Tab übernimmt die Ergänzung')
ok((await page.locator('.pal-row .pal-hl').first().textContent()) === 'Klavierstunde', 'Treffer sind markiert')
await page.fill('#suche-eingabe', '')
await page.keyboard.type('Wann hat Oma Helga Geburtstag?', { delay: 5 })
await page.waitForTimeout(150)
ok(/Oma Helga hat übermorgen Geburtstag/.test(await page.locator('.pal-answer').textContent()), 'Antwortkarte beantwortet die Geburtstagsfrage')
await page.keyboard.press('Enter')
await page.waitForTimeout(200)
ok(/wa\.me\/491712223344/.test(decodeURIComponent(await page.evaluate(() => window.__wa || ''))), 'Enter startet den WhatsApp-Glückwunsch')
ok(!(await page.locator('.pal').isVisible().catch(() => false)), 'Suche schließt nach der Aktion')

await page.keyboard.press('/')
await page.waitForTimeout(200)
ok(await page.locator('.pal').isVisible(), '„/“ öffnet die Suche')
await page.keyboard.type('Ben Dienstag 17 Uhr Schwimmen', { delay: 5 })
await page.waitForTimeout(150)
ok(/Eintragen: Schwimmen/.test(await page.locator('.pal-row.on').textContent()), 'Satz mit Uhrzeit wird zur Eintragen-Aktion')
await page.keyboard.press('Enter')
await page.waitForTimeout(300)
let db = await store()
const ben = db.members.find((m) => m.name === 'Ben')
ok(db.events.some((e) => e.title === 'Schwimmen' && e.member_id === ben.id && e.on_date === nextWd(1) && e.at_time === '17:00'), 'Termin für Ben am Dienstag um 17:00 angelegt')

await page.keyboard.press('Control+k')
await page.keyboard.type('Milch auf die Liste', { delay: 5 })
await page.keyboard.press('Enter')
await page.waitForTimeout(250)
db = await store()
ok(db.items.some((i) => i.list === 'einkauf' && i.text === 'Milch'), '„Milch auf die Liste“ landet auf der Einkaufsliste')

await page.keyboard.press('Control+k')
await page.keyboard.type('Fotobuch', { delay: 5 })
await page.waitForTimeout(150)
await page.locator('.pal-row', { hasText: 'Im Gedächtnispalast' }).click()
await page.waitForTimeout(300)
ok((await page.textContent('body')).includes('Danach suche ich hier nach „Fotobuch“'), 'Verschlossener Palast: Suchbegriff wird bis nach dem Entsperren aufgehoben')

console.log('— Heute')
await page.locator('.navbtn', { hasText: 'Heute' }).click()
await page.waitForTimeout(300)
const lage = await page.textContent('.lage')
ok(/^Heute /.test(lage.trim()) && (await page.locator('.lage .lage-mark').count()) >= 1, 'Tageslage fasst den Tag in Sätzen mit Markierungen zusammen', lage)
const num0 = await page.textContent('.ab-sheet:not(.ab-tear .ab-sheet) .ab-num')
await page.locator('.ab-nav button[aria-label^="Nächster Tag"]').click()
await page.waitForTimeout(80)
ok(await page.locator('.ab-tear').count() === 1, 'Blatt wird abgerissen (Animation läuft)')
await page.waitForTimeout(700)
const tomorrow = new Date(); tomorrow.setDate(tomorrow.getDate() + 1)
ok((await page.textContent('.ab-pad .ab-num')) === String(tomorrow.getDate()), 'Abreißkalender zeigt morgen', { num0 })
ok(/^Morgen /.test((await page.textContent('.lage')).trim()), 'Tageslage spricht jetzt über morgen')
await page.locator('.ab-nav button', { hasText: 'Heute' }).click()
await page.waitForTimeout(200)
ok((await page.textContent('.ab-pad .ab-num')) === String(new Date().getDate()), '„Heute“ springt zurück')

await page.evaluate(() => document.querySelector('.planer').scrollIntoView({ block: 'center' }))
await page.waitForTimeout(150)
const benCol = page.locator('.planer .pl-col').nth(3)
const box = await benCol.boundingBox()
const view = await page.locator('.planer .pl-scroll').boundingBox()
await page.mouse.click(box.x + box.width / 2, Math.min(view.y + view.height - 30, 870))
await page.waitForTimeout(300)
ok((await page.locator('#f-who option:checked').textContent()) === 'Ben' && /^\d\d:\d\d$/.test(await page.inputValue('#f-time')), 'Klick in Bens Spalte öffnet einen Termin für Ben mit Uhrzeit')
await page.locator('.sheet .x').click()
await page.waitForTimeout(200)

console.log('— Eselsohr')
const row = page.locator('.row-wrap', { hasText: 'Praxis · belegt' }).first()
await row.hover()
await row.locator('.dogear').click()
await page.waitForTimeout(300)
db = await store()
const jan = db.members.find((m) => m.name === 'Jan')
ok((jan.pins || []).length === 1, 'Ecke knicken merkt den Termin')
ok((await page.textContent('body')).includes('mit Eselsohr markiert'), 'Bereich „Gemerkt“ erscheint')
ok((await page.textContent('.blatt-ohr')) === '1', 'Das Eselsohr am Blatt zählt mit')

console.log('— Erscheinungsbild')
await page.locator('.userchip').click()
await page.waitForTimeout(200)
await page.locator('.themeseg button', { hasText: 'Dunkel' }).click()
ok((await page.getAttribute('html', 'data-theme')) === 'dark', 'Dunkel setzt das Erscheinungsbild')
await page.locator('.themeseg button', { hasText: 'Automatisch' }).click()
ok((await page.getAttribute('html', 'data-theme')) === null, 'Automatisch folgt wieder dem Gerät')

console.log('— Kalender')
await page.locator('.navbtn', { hasText: 'Kalender' }).click()
await page.waitForTimeout(250)
ok((await page.locator('.month .kw').count()) >= 4, 'Kalenderwochen stehen links')
const decY = new Date().getMonth() === 11 ? 0 : 11 - new Date().getMonth()
for (let i = 0; i < decY; i++) await page.locator('.seg button[aria-label="Nächster Monat"]').click()
await page.waitForTimeout(200)
ok((await page.textContent('.month')).includes('1. Weihnachtstag'), 'Feiertage stehen im Monatsblatt')
ok(await page.locator('.mday.fei', { hasText: '25' }).count() === 1, 'Feiertag ist rot markiert')
await page.locator('.seg button', { hasText: 'Heute' }).click()
await page.locator('.chip', { hasText: 'Ich + Kinder' }).click()
await page.waitForTimeout(200)
const cols = await page.locator('.day-panel .pl-name').allTextContents()
ok(cols.length === 3 && cols.join(' ').includes('Jan') && !cols.join(' ').includes('Anne'), 'Tagesplaner zeigt nur Ich + Kinder als Spalten', cols)

console.log('— Handy')
const m = await (await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true })).newPage()
await m.goto('http://localhost:4173')
await m.evaluate(() => localStorage.clear())
await m.reload(); await m.waitForTimeout(300)
await m.locator('button', { hasText: 'Erst mal die Demo ansehen' }).click()
await m.waitForTimeout(500)
ok(await m.locator('.dock').isVisible() && !(await m.locator('.register').isVisible()), 'Handy: Dock statt Reiter')
ok((await m.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)), 'Handy: kein seitliches Scrollen')
m.on('pageerror', (e) => errs.push(e.message))
const mStore = () => m.evaluate(() => JSON.parse(localStorage.getItem('eselsohr-v1')))

console.log('— Handy: Heute auf einen Blick')
ok(await m.locator('.glance').isVisible() && !(await m.locator('.h-grid').count()), 'Handy zeigt „Heute auf einen Blick“ statt der Planer-Seite')
ok(!(await m.locator('.searchpill').isVisible()), 'Kopfzeile bleibt einzeilig – die Suche sitzt im Dock')
// Was über dem Dock sichtbar ist, ohne einen Millimeter zu scrollen
const fold = await m.evaluate(() => {
  const line = window.innerHeight - document.querySelector('.dock-in').getBoundingClientRect().height - 12
  const top = (sel) => { const el = document.querySelector(sel); return el ? el.getBoundingClientRect() : null }
  return {
    line,
    kopf: top('.g-head')?.bottom,
    kinder: top('.g-kids')?.bottom,
    heute: top('.g-day > :not(.g-now)')?.bottom,
    hoehe: document.documentElement.scrollHeight,
  }
})
ok(fold.kopf < fold.line && fold.kinder < fold.line && fold.heute < fold.line, 'Tag, Kinder und der heutige Plan stehen ohne Scrollen auf dem ersten Bildschirm', fold)
ok(fold.hoehe < 1600, 'Die ganze Seite ist kurz (vorher 2674 px)', fold.hoehe)
ok((await m.textContent('.g-kid >> nth=0')).includes('Emma') && /Schule|jetzt|zu Hause/.test(await m.textContent('.g-kid >> nth=0')), 'Kinder-Kachel sagt, wo Emma ist', await m.textContent('.g-kid >> nth=0'))
ok((await m.textContent('.g-kid >> nth=1')).includes('Betreuungszeiten'), 'Kinder ohne Zeiten laden zum Anlegen ein')
ok(await m.locator('.g-day .row-wrap.is-next .g-in').count() === 1 || !(await m.locator('.g-day .row-wrap:not(.past)').count()), 'Der nächste Termin ist hervorgehoben (mit „in … / läuft“)')
ok((await m.textContent('#anfragen-karte')).includes('Wartet auf dich') && (await m.locator('.g-wait .row').count()) === 3, '„Wartet auf dich“ sammelt Anfrage, offenen Kindertermin und Geburtstag')
ok((await m.textContent('.tab:has-text("Listen") .cnt.soft')) === '3', 'Listen-Reiter zeigt offene Punkte als graue Zahl')

// Familienplaner: zugeklappt das Tagesband, aufgeklappt der große Planer
ok(await m.locator('#planer-klapp .band').isVisible() && !(await m.locator('#planer-klapp .planer').count()), 'Zugeklappt zeigt der Familienplaner das Tagesband')
await m.locator('#planer-klapp > summary').click()
await m.waitForTimeout(250)
ok(await m.locator('#planer-klapp .planer').isVisible() && !(await m.locator('#planer-klapp .band').count()), 'Aufklappen öffnet den Planer mit einer Spalte pro Person')
await m.locator('#planer-klapp > summary').click()
await m.waitForTimeout(200)
ok(!(await m.locator('#planer-klapp .planer').count()), 'Zuklappen räumt den Planer wieder weg')
await m.locator('#morgen-klapp > summary').click()
await m.waitForTimeout(200)
ok(await m.locator('#morgen-klapp .k-body .row').count() >= 1, '„Morgen“ klappt mit den Terminen von morgen auf')

// Blättern: Pfeil, „Zurück zu heute“, Wischen über den Kopf
const tmr = new Date(); tmr.setDate(tmr.getDate() + 1)
await m.evaluate(() => window.scrollTo(0, 0))
await m.locator('.g-daynav button[aria-label^="Nächster Tag"]').click()
await m.waitForTimeout(80)
ok(await m.locator('.g-head .ab-tear').count() === 1, 'Handy: Auch der kleine Block reißt sein Blatt ab')
await m.waitForTimeout(700)
ok((await m.textContent('.g-head .ab-pad .ab-num')) === String(tmr.getDate()) && await m.locator('.g-back').isVisible(), 'Pfeil blättert auf morgen, „Zurück zu heute“ erscheint')
await m.locator('.g-back').click()
await m.waitForTimeout(300)
ok((await m.textContent('.g-head .ab-pad .ab-num')) === String(new Date().getDate()) && !(await m.locator('.g-back').count()), '„Zurück zu heute“ springt zurück')
const hb = await m.locator('.g-hello').boundingBox()
await m.mouse.move(hb.x + hb.width - 10, hb.y + 20)
await m.mouse.down()
await m.mouse.move(hb.x + 10, hb.y + 24, { steps: 6 })
await m.mouse.up()
await m.waitForTimeout(700)
ok((await m.textContent('.g-head .ab-pad .ab-num')) === String(tmr.getDate()), 'Nach links wischen blättert einen Tag weiter')
await m.locator('.g-back').click()
await m.waitForTimeout(300)

// Handeln direkt aus „Wartet auf dich“
await m.locator('.g-wait .row', { hasText: 'Kinderarzt' }).locator('button', { hasText: 'Übernehmen' }).click()
await m.waitForTimeout(250)
const mdb = await mStore()
ok(mdb.events.find((e) => e.title === 'Kinderarzt Vorsorge').zust === mdb.members.find((x) => x.name === 'Jan').id, '„Übernehmen“ teilt Jan für den Kinderarzt ein')
ok(!(await m.locator('.g-wait .row', { hasText: 'Kinderarzt' }).count()), '… und die Zeile ist erledigt')

// Kinder-Kachel öffnet den Tag des Kindes im Kalender
await m.locator('.g-kid', { hasText: 'Emma' }).click()
await m.waitForTimeout(350)
ok(await m.locator('.kal .month').isVisible() && (await m.locator('.kal-tools .chip.off').count()) === 3, 'Kachel öffnet den Kalender nur mit Emma')
ok(await m.locator('.day-panel .card .row').first().isVisible() && await m.locator('#kal-planer .band').isVisible(), 'Kalender am Handy: Tagesliste zuerst, Tagesplaner aufklappbar')
await m.locator('.chip', { hasText: 'Alle zeigen' }).click()

await m.locator('.tab', { hasText: 'Mehr' }).click()
await m.waitForTimeout(250)
ok(await m.locator('.more-tile', { hasText: 'Gedächtnispalast' }).isVisible(), '„Mehr“ führt zu Palast, Familie und Profil')

ok(!errs.length, 'Keine Fehler in der Konsole', errs)
await browser.close()
console.log(fails ? `\n${fails} FEHLER` : '\nALLE OBERFLÄCHEN-TESTS BESTANDEN')
process.exitCode = fails ? 1 : 0
